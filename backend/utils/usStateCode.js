/** @returns {string|null} Two-letter USPS code or null if unrecognized. */
function normalizeUsStateCode(rawState, isoRegion) {
    const fromIso = String(isoRegion || '')
        .replace(/^US-/i, '')
        .trim()
        .toUpperCase();
    if (/^[A-Z]{2}$/.test(fromIso)) return fromIso;

    const raw = String(rawState || '').trim();
    if (!raw) return null;
    if (/^[A-Za-z]{2}$/.test(raw)) return raw.toUpperCase();

    const byName = STATE_NAME_TO_CODE[raw.toLowerCase()];
    if (byName) return byName;

    return null;
}

function isUsStateCode(code) {
    const c = String(code || '').trim().toUpperCase();
    return /^[A-Z]{2}$/.test(c) && Boolean(STATE_CODE_TO_NAME[c]);
}

